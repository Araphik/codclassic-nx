import re,collections
# ORDMAP: the codegen output with its 'Cannot resolve ordinal N from x360shared (thunk 0x...)' lines
txt=open(__import__('os').environ['ORDMAP']).read()
m=collections.defaultdict(dict)
for ordn,lib,addr in re.findall(r'Cannot resolve ordinal (\d+) from (\w+) \(thunk 0x([0-9A-F]{8})\)',txt):
    a=int(addr,16)
    mod={0x82:'default',0x85:'cgame_sp',0x89:'ui_sp',0x87:'game_sp',0x8A:'x360shared'}[a>>24]
    m[mod][a]=(lib,int(ordn))
hdr='''// Auto-generated by gen_thunks.py: import thunks for guest-module (x360shared.xdl) exports.
// ReXGlue resolves kernel/xam imports at codegen time, but not imports between
// game modules, so these thunks look the export up at runtime and dispatch to
// the recompiled function in the loaded module.
#include "codclassic_pch.h"
#include <rex/system/kernel_state.h>
#include <rex/system/xmodule.h>
#include <rex/system/user_module.h>
#include <atomic>

namespace {
uint32_t ResolveGuestExport(const char* lib, uint16_t ordinal) {
  auto* ks = REX_KERNEL_STATE();
  std::string name = std::string(lib) + ".xdl";
  uint32_t addr = 0;
  // Static imports are normally loaded by the XEX loader before the importer
  // runs; LoadUserModule returns the already-loaded module if present.
  if (auto mod = ks->GetModule(std::string(R"(game:\)") + name)) {
    addr = mod->GetProcAddressByOrdinal(ordinal);
  } else if (auto um = ks->LoadUserModule(std::string(R"(game:\)") + name)) {
    addr = um->GetProcAddressByOrdinal(ordinal);
  }
  if (!addr) {
    REXLOG_ERROR("codclassic: cannot resolve {}:{} at runtime", name, ordinal);
  } else {
    REXLOG_INFO("codclassic: {}:{} -> 0x{:08X}", name, ordinal, addr);
  }
  return addr;
}
// Resolving may load the module and run its DllMain on this same guest
// context. Snapshot and restore it here, through a plain (non-__restrict)
// pointer, so the compiler cannot assume the context is untouched.
[[gnu::noinline]] uint32_t ResolveGuestExportPreservingContext(PPCContext* c, const char* lib,
                                                               uint16_t ordinal) {
  PPCContext saved = *c;
  uint32_t addr = ResolveGuestExport(lib, ordinal);
  *c = saved;
  return addr;
}
}  // namespace

#define GUEST_IMPORT_THUNK(fn, lib, ord)                                   \\
  static std::atomic<uint32_t> fn##_target{0};                             \\
  DEFINE_REX_FUNC(fn) {                                                    \\
    uint32_t t = fn##_target.load(std::memory_order_relaxed);              \\
    if (!t) {                                                              \\
      t = ResolveGuestExportPreservingContext(&ctx, lib, ord);             \\
      fn##_target.store(t);                                                \\
    }                                                                      \\
    if (t == 0x8A0117C8) REXLOG_INFO("codclassic: init args r4={:08X} r5={:08X} r6={:08X}", ctx.r4.u32, ctx.r5.u32, ctx.r6.u32); \\
    REX_CALL_INDIRECT_FUNC(t);                                             \\
  }

'''
for mod,th in m.items():
    with open(f'src/guest_imports_{mod}.cpp','w') as f:
        f.write(hdr)
        for a in sorted(th):
            lib,o=th[a]; f.write(f'GUEST_IMPORT_THUNK(sub_{a:08X}, "{lib}", {o})\n')
    print(mod,len(th))
