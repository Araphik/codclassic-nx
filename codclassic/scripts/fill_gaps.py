#!/usr/bin/env python3
"""Covers every stretch of code that no recompiled function owns.

Indirect calls (vtables, callback tables) and switch jump tables the analysis missed land in
code nobody owns and die with "Call to invalid or unregistered function". This declares a
function at the start of every such gap, runs codegen, and repeats on what is still uncovered
(the codegen stops each new function at its first unconditional branch, so a long gap needs
several rounds). Padding and data at a gap start are skipped by moving to the first real
instruction the codegen decoded.

Writes <mod>_gaps.toml for each module (included from the manifest).
usage: fill_gaps.py <rexglue> <app dir>
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gaps as G  # noqa: E402

MODULES = ['default', 'x360shared', 'game_sp', 'cgame_sp', 'ui_sp']
PADDING = re.compile(r'^(nop|\.long 0x0+|\.long 0x0|invalid.*|\?\?.*|)$')


def write_hints(app, mod, addrs):
    with open(os.path.join(app, f'{mod}_gaps.toml'), 'w') as f:
        f.write('# Generated by scripts/fill_gaps.py: starts of code no analyzed function covered\n')
        f.write('# (reached only through pointers or missed jump tables).\n[functions]\n')
        for a in sorted(addrs):
            f.write(f'0x{a:08X} = {{}}\n')


def main():
    rexglue, app = sys.argv[1], sys.argv[2]
    hints = {m: set() for m in MODULES}
    dead = {m: set() for m in MODULES}     # gap starts proven to be padding/data
    for rnd in range(40):
        for m in MODULES:
            write_hints(app, m, hints[m])
        for fix in range(30):
            r = subprocess.run([rexglue, 'codegen', 'codclassic_manifest.toml'], cwd=app,
                               capture_output=True, text=True)
            if r.returncode == 0:
                break
            txt = r.stdout + r.stderr
            failed = re.search(r"Analysis failed for '(\w+)'", txt)
            targets = re.findall(r'  0x([0-9A-F]{8}) from 0x[0-9A-F]{8}: .* - target not in any function', txt)
            outside = re.findall(r'function 0x([0-9A-F]{8}) not in any code region', txt)
            if not failed or not (targets or outside):
                print(txt[-3000:])
                sys.exit(f'codegen failed in round {rnd}')
            m = failed.group(1)
            for t in outside:
                hints[m].discard(int(t, 16))
                dead[m].add(int(t, 16))
            for t in targets:
                hints[m].add(int(t, 16))
            write_hints(app, m, hints[m])
        else:
            sys.exit(f'codegen kept failing in round {rnd}')
        added = 0
        for m in MODULES:
            gen = os.path.join(app, 'generated', m)
            gaps, fns = G.gaps(gen, minimum=8)
            for lo, hi in gaps:
                if lo in dead[m]:
                    continue
                if lo in hints[m]:
                    # Declared last round and still a gap: the codegen emitted nothing usable
                    # there (data). Give up on this start.
                    asm = fns.get(lo, [])
                    dead[m].add(lo)
                    hints[m].discard(lo)
                    continue
                hints[m].add(lo)
                added += 1
            # Declared starts whose first instructions are padding: move to the first real one.
            for a in list(hints[m]):
                asm = fns.get(a)
                if not asm:
                    continue
                k = 0
                while k < len(asm) and PADDING.match(asm[k]):
                    k += 1
                if k:
                    hints[m].discard(a)
                    dead[m].add(a)
                    if k < len(asm):
                        hints[m].add(a + 4 * k)
                        added += 1
        total = sum(len(h) for h in hints.values())
        left = {m: len(G.gaps(os.path.join(app, 'generated', m), minimum=8)[0]) for m in MODULES}
        print(f'round {rnd}: +{added} starts, {total} declared, gaps left {left}')
        if added == 0:
            break
    for m in MODULES:
        write_hints(app, m, hints[m])
    subprocess.run([rexglue, 'codegen', 'codclassic_manifest.toml'], cwd=app, check=True,
                   capture_output=True)


if __name__ == '__main__':
    main()
