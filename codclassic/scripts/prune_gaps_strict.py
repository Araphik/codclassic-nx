#!/usr/bin/env python3
"""Second, strict pass over <mod>_gaps.toml: keeps only hints that leave the generated C++ of
every original function byte-for-byte identical.

prune_gaps.py only compared instruction counts. That missed hints placed on the codegen's
special helpers (__savegprlr_N / __restgprlr_N / __savefpr_N ...), which are emitted under their
own names, not as sub_X with asm comments, so they looked like uncovered code. A hint there
turned every `__savegprlr_14(ctx, base)` in prologues into a call to a generically recompiled
sub_821EC430, and the game crashed at the splash screen. Likewise a hint on a label inside a
function turns a `goto` into a tail call.

Any hint whose sub_X name appears in a changed original body is dropped; repeat until no
original body changes.

usage: prune_gaps_strict.py <rexglue> <app dir>
"""
import glob
import os
import re
import subprocess
import sys

MODULES = ['default', 'x360shared', 'game_sp', 'cgame_sp', 'ui_sp']
FUNC = re.compile(r'^(?:DEFINE_REX_FUNC|PPC_FUNC_IMPL)\((?:__imp__)?(sub_[0-9A-F]{8}|__\w+)\)')


def bodies(gen):
    out = {}
    for f in sorted(glob.glob(os.path.join(gen, 'codclassic_recomp.*.cpp'))):
        cur = None
        for line in open(f, encoding='utf-8'):
            m = FUNC.match(line)
            if m:
                cur = m.group(1)
                out[cur] = []
                continue
            if cur:
                if line.startswith('}'):
                    cur = None
                else:
                    out[cur].append(line)
    return out


def read_hints(app, m):
    return {int(x, 16) for x in re.findall(r'^0x([0-9A-F]{8}) =', open(os.path.join(app, f'{m}_gaps.toml')).read(), re.M)}


def write_hints(app, m, hints):
    with open(os.path.join(app, f'{m}_gaps.toml'), 'w') as f:
        f.write('# Generated by scripts/fill_gaps.py + prune_gaps.py + prune_gaps_strict.py: starts of code\n')
        f.write('# no analyzed function covered, kept only if every original function stays identical.\n[functions]\n')
        for a in sorted(hints):
            f.write(f'0x{a:08X} = {{}}\n')


def codegen(rexglue, app):
    subprocess.run([rexglue, 'codegen', 'codclassic_manifest.toml'], cwd=app, check=True, capture_output=True)


def main():
    rexglue, app = sys.argv[1], sys.argv[2]
    hints = {m: read_hints(app, m) for m in MODULES}
    for m in MODULES:
        write_hints(app, m, set())
    codegen(rexglue, app)
    base = {m: bodies(os.path.join(app, 'generated', m)) for m in MODULES}
    # Addresses the codegen gives special names to (save/restore helpers etc.).
    special = {m: set() for m in MODULES}
    for m in MODULES:
        init = open(os.path.join(app, 'generated', m, 'codclassic_init.cpp'), encoding='utf-8').read()
        for a, name in re.findall(r'\{ 0x([0-9A-F]{8}), (\w+) \}', init):
            if not name.startswith('sub_'):
                special[m].add(int(a, 16))
        before = len(hints[m])
        hints[m] -= special[m]
        print(f'{m}: dropped {before - len(hints[m])} hints on specially named helpers')
    for rnd in range(30):
        for m in MODULES:
            write_hints(app, m, hints[m])
        codegen(rexglue, app)
        changed = 0
        dropped = 0
        for m in MODULES:
            now = bodies(os.path.join(app, 'generated', m))
            for name, body in base[m].items():
                if now.get(name) == body:
                    continue
                changed += 1
                new_text = ''.join(now.get(name, []))
                old_text = ''.join(body)
                for a in re.findall(r'sub_([0-9A-F]{8})', new_text):
                    if f'sub_{a}' not in old_text and int(a, 16) in hints[m]:
                        hints[m].discard(int(a, 16))
                        dropped += 1
                if now.get(name) is None:
                    sys.exit(f'{m}: original {name} disappeared')
        print(f'round {rnd}: {changed} original bodies differ, dropped {dropped}, kept {sum(map(len, hints.values()))}')
        if changed == 0:
            return
        if dropped == 0:
            sys.exit('bodies differ but no hint to blame')
    sys.exit('did not converge')


if __name__ == '__main__':
    main()
