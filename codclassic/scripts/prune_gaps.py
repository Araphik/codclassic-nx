#!/usr/bin/env python3
"""Keeps only the gap hints that leave every originally analyzed function intact.

A "gap" computed as start + 4 * instructions can lie inside a real function that embeds a jump
table or skips padding; a hint there splits that function. Compare each function's instruction
count without and with the gap hints, drop every hint between the start of a function that
changed and the next original function start, and repeat until nothing original changes.

usage: prune_gaps.py <rexglue> <app dir>   (expects <mod>_gaps.toml from fill_gaps.py)
"""
import bisect
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gaps as G  # noqa: E402

MODULES = ['default', 'x360shared', 'game_sp', 'cgame_sp', 'ui_sp']


def read_hints(app, m):
    return {int(x, 16) for x in re.findall(r'^0x([0-9A-F]{8}) =', open(os.path.join(app, f'{m}_gaps.toml')).read(), re.M)}


def write_hints(app, m, hints):
    with open(os.path.join(app, f'{m}_gaps.toml'), 'w') as f:
        f.write('# Generated by scripts/fill_gaps.py + prune_gaps.py: starts of code that no analyzed\n')
        f.write('# function covered (reached only through pointers or missed jump tables).\n[functions]\n')
        for a in sorted(hints):
            f.write(f'0x{a:08X} = {{}}\n')


def codegen(rexglue, app):
    r = subprocess.run([rexglue, 'codegen', 'codclassic_manifest.toml'], cwd=app, capture_output=True, text=True)
    return r.returncode == 0, r.stdout + r.stderr


def snapshot(app):
    return {m: {a: len(asm) for a, asm in G.functions(os.path.join(app, 'generated', m)).items()} for m in MODULES}


def main():
    rexglue, app = sys.argv[1], sys.argv[2]
    hints = {m: read_hints(app, m) for m in MODULES}
    for m in MODULES:
        write_hints(app, m, set())
    ok, txt = codegen(rexglue, app)
    assert ok, txt[-2000:]
    base = snapshot(app)
    for rnd in range(20):
        for m in MODULES:
            write_hints(app, m, hints[m])
        ok, txt = codegen(rexglue, app)
        if not ok:
            # A dropped hint was the target of a branch from another hint: drop that one too.
            fail = re.search(r"Analysis failed for '(\w+)'", txt)
            srcs = re.findall(r'from 0x([0-9A-F]{8}): .* - target not in any function', txt)
            if not fail or not srcs:
                sys.exit(txt[-3000:])
            m = fail.group(1)
            starts = sorted(hints[m])
            for s in srcs:
                i = bisect.bisect_right(starts, int(s, 16)) - 1
                if i >= 0:
                    hints[m].discard(starts[i])
            print(f'round {rnd}: codegen failed in {m}, dropped {len(srcs)} hint(s) branching to dropped code')
            continue
        now = snapshot(app)
        dropped = 0
        for m in MODULES:
            orig = sorted(base[m])
            for s in orig:
                if now[m].get(s) is None:
                    # Swallowed by the function of the nearest hint before it.
                    before = [h for h in hints[m] if h < s]
                    if before:
                        hints[m].discard(max(before))
                        dropped += 1
                    continue
                if now[m].get(s) != base[m][s]:
                    i = bisect.bisect_right(orig, s)
                    nxt = orig[i] if i < len(orig) else 0xFFFFFFFF
                    bad = {h for h in hints[m] if s < h < nxt}
                    hints[m] -= bad
                    dropped += len(bad)
        changed = sum(1 for m in MODULES for s in base[m] if now[m].get(s) != base[m][s])
        print(f'round {rnd}: {changed} original functions changed, dropped {dropped} hints, '
              f'kept {sum(len(h) for h in hints.values())}')
        if changed == 0:
            break
    else:
        sys.exit('did not converge')


if __name__ == '__main__':
    main()
